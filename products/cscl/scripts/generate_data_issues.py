#!/usr/bin/env python3
"""
Generate data_issues.md from seeds/known_differences.csv, the source of truth for CSCL's
known differences from the previous production release.

Usage:
    python scripts/generate_data_issues.py          # rewrite data_issues.md
    python scripts/generate_data_issues.py --check  # exit 1 if data_issues.md is stale
"""

import argparse
import csv
import re
import sys
from pathlib import Path

PRODUCT_ROOT = Path(__file__).resolve().parent.parent
SEED_PATH = PRODUCT_ROOT / "seeds" / "known_differences.csv"
OUTPUT_PATH = PRODUCT_ROOT / "data_issues.md"

INTRO = """\
# CSCL Data Issues

<!-- Generated by scripts/generate_data_issues.py from seeds/known_differences.csv. Edit
the seed, then rerun the script; don't edit this file by hand. -->

Known differences between our output and production, and source-data problems, each with a
stable ID. Code comments, dbt descriptions and the `qa__diffs_*` models cite these IDs where
a diff is accounted for, so an ID is never reused or renumbered.

This file is an index, generated from
[seeds/known_differences.csv](./seeds/known_differences.csv) (column definitions in
[seeds/seeds.yml](./seeds/seeds.yml)). Each issue's analysis, evidence and history lives in
the data-engineering tracker (beads, prefix `inv`), in the bead listed below. Some issues
are also tracked in GR's
[discrepancy log](https://nyco365.sharepoint.com/:w:/r/sites/NYCPLANNING/itd/edm/Shared%20Documents/DOCUMENTATION/GRU/CSCL/ETL/DE%20Pipeline%20-%20Project%20Tracking/Data%20Discrepancy%20Tracking/LION%20Flat%20Files%20%E2%80%93%20Data%20DiscrepancyIssue%20Tracking.docx?d=w60907e50f8044bd9bffe2508a299035f&csf=1&web=1&e=aZ59n8).
The spec for each output is [design_doc.md](./design_doc.md).

| Status | Meaning |
|---|---|
| **Open** | Unexplained, or explained but undecided. |
| **Accepted** | Understood and deliberately not changing. Usually GR confirmed. |
| **Watch** | Resolved, can recur. Check each release. |
| **Fixed** | No longer differs. Kept so the ID isn't reused. |

**Cause**: `prod_bug` prod is wrong, ours is right; `source_vintage` the two sides were
built from different source extracts; `source_defect` bad source data both sides see;
`ours_intentional` we deliberately differ from prod; `ours_bug_fixed` was ours, now fixed;
`ours_bug` ours, not yet fixed; `gr_pending` waiting on GR to say which side is right;
`unknown`.

**Last verified** is the product version the issue was last checked against. The bead is
authoritative where it disagrees with this table.
"""

BUG_INTRO = """\
## Older "Bug NNN" references

Some comments and beads cite `Bug NNN`, from the bug write-ups that preceded these IDs.
"""


def read_seed(path: Path = SEED_PATH) -> list[dict[str, str]]:
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def _table(headers: list[str], rows: list[list[str]]) -> str:
    lines = [
        "| " + " | ".join(headers) + " |",
        "|" + "---|" * len(headers),
    ]
    lines += ["| " + " | ".join(_cell(c) for c in row) + " |" for row in rows]
    return "\n".join(lines) + "\n"


def _bug_number(alias: str) -> str | None:
    match = re.match(r"Bug (\d{3})", alias)
    return match.group(1) if match else None


def render(rows: list[dict[str, str]]) -> str:
    issues = _table(
        [
            "ID",
            "Output",
            "Scope",
            "Difference",
            "Cause",
            "Status",
            "Last verified",
            "Bead",
        ],
        [
            [
                r["id"],
                r["output"],
                r["scope"],
                r["description"],
                f"`{r['cause']}`",
                r["status"].capitalize(),
                r["last_verified"],
                r["reference"],
            ]
            for r in rows
        ],
    )

    bugs: dict[str, list[str]] = {}
    for r in rows:
        for alias in filter(None, (a.strip() for a in r["alias"].split(";"))):
            number = _bug_number(alias)
            if number is None:
                raise ValueError(f"{r['id']}: alias {alias!r} isn't 'Bug NNN ...'")
            item = alias.removeprefix(f"Bug {number}").strip()
            bugs.setdefault(number, []).append(
                f"{r['id']} ({item})" if item else r["id"]
            )
    bug_table = _table(
        ["Bug", "ID"],
        [[number, ", ".join(ids)] for number, ids in sorted(bugs.items())],
    )

    return f"{INTRO}\n## Issues\n\n{issues}\n{BUG_INTRO}\n{bug_table}"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="don't write; exit 1 if data_issues.md differs from the seed",
    )
    args = parser.parse_args()

    content = render(read_seed())
    if args.check:
        if OUTPUT_PATH.read_text() != content:
            print(
                f"✗ {OUTPUT_PATH.name} is stale: run scripts/generate_data_issues.py",
                file=sys.stderr,
            )
            sys.exit(1)
        print(f"✓ {OUTPUT_PATH.name} matches {SEED_PATH.name}")
        return

    OUTPUT_PATH.write_text(content)
    print(f"✓ Wrote {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
