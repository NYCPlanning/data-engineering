#!/usr/bin/env bash
# Regenerates requirements.txt for the devstack python image from the repo's uv.lock:
# dispatch with its worker + dagster extras, plus the Dagster webserver and Postgres storage
# at the versions apps/dagster locks. Run from anywhere after `uv lock`.
set -euo pipefail
root="$(git -C "$(dirname "$0")" rev-parse --show-toplevel)"
cd "$root"
ver() { awk -v n="$1" '$0=="name = \""n"\""{getline; gsub(/version = |"/,""); print; exit}' uv.lock; }
{
  echo "# Generated by apps/devstack/python/requirements.sh from uv.lock. Don't edit by hand."
  uv export --frozen --package dcpy-app-dispatch --extra worker --extra dagster \
    --no-hashes --no-emit-workspace --no-header --no-annotate
  echo "dagster-webserver==$(ver dagster-webserver)"
  echo "dagster-postgres==$(ver dagster-postgres)"
} > apps/devstack/python/requirements.txt
